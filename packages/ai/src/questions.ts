// Everything Jev is asked during triage, and the thresholds that read its answers. Edit wording
// here and nowhere else. Each question is one judgment about the state built in `jev.ts`; the
// truth tables in `decide.ts` turn the answers into a bucket. Who wrote the latest message is a
// fact code knows, so it picks the question set: `TRIAGE_QUESTIONS` when someone else did,
// `SENT_QUESTIONS` when the reader did.

/** Pinned so an alias move can't shift answers under tuned thresholds. Override per client. */
export const JEV_MODEL = "jev-1.14.0";

/** A Noul at or above this reads as yes. */
export const NOUL_YES = 0.7;
/** A Noul at or below this reads as no. Between the two, the judgment is unsettled. */
export const NOUL_NO = 0.3;

/**
 * Confidence ceiling when a judgment the table needed sat between the bands. Below the 0.85
 * auto-file threshold, so `laneFor` sends the thread to Unsure.
 */
export const UNSETTLED_CONFIDENCE_CAP = 0.5;

/** Token budget for `latest_message`. Jev reads up to 32k tokens per question. */
export const JEV_LATEST_MESSAGE_TOKENS = 8_000;
/** Token budget for each earlier message in `thread.earlier_messages`. */
export const JEV_EARLIER_MESSAGE_TOKENS = 400;
/** How many earlier messages, newest first, give the latest one its context. */
export const JEV_EARLIER_MESSAGES = 2;

/** Shared facts every question can lean on. Goes into the state once. */
export const READER_NOTE =
  "The reader owns this inbox. `latest_message` is the newest message in the thread and was sent to the reader.";

export interface NoulQuestion {
  type: "noul";
  instructions: string;
  criteria?: { true: string; false: string };
}

export const TRIAGE_QUESTIONS = {
  expects_reply: {
    type: "noul",
    instructions: "Does the sender of `latest_message` expect the reader to reply?",
    criteria: {
      true: "The sender asks the reader a question, asks them to decide or confirm something, or asks for something only the reader can send.",
      false:
        "The sender informs, confirms, or thanks the reader and would not be waiting for an answer.",
    },
  },
  automated: {
    type: "noul",
    instructions: "Was `latest_message` generated by a system rather than written by a person?",
    criteria: {
      true: "A receipt, alert, password reset, shipping update, calendar notice, or other message a system sends on its own.",
      false: "A person wrote it to the reader, even if it uses a template or a signature.",
    },
  },
  bulk: {
    type: "noul",
    instructions:
      "Is `latest_message` bulk mail sent to many people, such as a newsletter or a promotion?",
    criteria: {
      true: "A newsletter, marketing offer, sale, digest, or announcement sent to a mailing list.",
      false:
        "A message to the reader personally, or a notice about the reader's own account or order.",
    },
  },
  promises_follow_up: {
    type: "noul",
    instructions:
      "Does the sender of `latest_message` say they will get back to the reader or send something later?",
    criteria: {
      true: "The sender says they are checking on something, will reply later, or will send something the reader is waiting for.",
      false: "The sender gives no sign that more is coming from their side.",
    },
  },
  concerns_reader: {
    type: "noul",
    instructions:
      "Is `latest_message` about something the reader is personally involved in, such as their account, order, payment, booking, or a project they work on?",
    criteria: {
      true: "A receipt for the reader's purchase, a security alert on their account, or an update on work they take part in.",
      false: "General news, marketing, or activity the reader has no part in.",
    },
  },
} as const satisfies Record<string, NoulQuestion>;

export type Judgment = keyof typeof TRIAGE_QUESTIONS;
export const JUDGMENTS = Object.keys(TRIAGE_QUESTIONS) as Judgment[];

/** The state's shared fact when the reader wrote the latest message. */
export const SENT_NOTE =
  "The reader owns this inbox and wrote `latest_message`, the newest message in the thread. It went to the other people in the thread.";

const ASKS_NOTHING =
  'An offer such as "let me know if you need anything" or "happy to help" asks for nothing.';

/**
 * Asked only when the reader wrote the latest message. Two judgments rather than one "asks for a
 * response or action", so each one is a single thing a person could point to, plus whether
 * software sent it on the reader's behalf (a sign-in link asks for a click, not a reply).
 */
export const SENT_QUESTIONS = {
  reader_asks_question: {
    type: "noul",
    instructions: "Does `latest_message` ask its recipients a question they need to answer?",
    criteria: {
      true: "The reader asks something the recipients have to answer, such as a date, a price, a yes or no, or a choice between options.",
      false: `The reader answers, confirms, thanks, or informs. ${ASKS_NOTHING}`,
    },
  },
  reader_requests_action: {
    type: "noul",
    instructions: "Does `latest_message` ask its recipients to send or do something?",
    criteria: {
      true: "The reader asks them to send a file or information, sign, approve, review, pay, or take another step.",
      false: `The reader sends what was asked for, confirms, thanks, or says what they will do themselves. ${ASKS_NOTHING}`,
    },
  },
  sent_by_system: {
    type: "noul",
    instructions: "Was `latest_message` generated by software rather than written by a person?",
    criteria: {
      true: "A sign-in link, verification code, receipt, notification, or other message an app sends on its own from the reader's address.",
      false: "A person wrote it, even if it uses a template or a signature.",
    },
  },
} as const satisfies Record<string, NoulQuestion>;

export type SentJudgment = keyof typeof SENT_QUESTIONS;
export const SENT_JUDGMENTS = Object.keys(SENT_QUESTIONS) as SentJudgment[];
