// Everything Jev is asked during triage, and the thresholds that read its answers. Edit wording
// here and nowhere else. Each question is one judgment about the state built in `jev.ts`; the
// truth table in `decide.ts` turns the answers into a bucket.

/** Pinned so an alias move can't shift answers under tuned thresholds. Override per client. */
export const JEV_MODEL = "jev-1.14.0";

/** A Noul at or above this reads as yes. */
export const NOUL_YES = 0.7;
/** A Noul at or below this reads as no. Between the two, the judgment is unsettled. */
export const NOUL_NO = 0.3;

/**
 * Confidence ceiling when a judgment the table needed sat between the bands. Below the 0.85
 * auto-file threshold, so `laneFor` sends the thread to Unsure.
 */
export const UNSETTLED_CONFIDENCE_CAP = 0.5;

/** Token budget for `latest_message`. Jev reads up to 32k tokens per question. */
export const JEV_LATEST_MESSAGE_TOKENS = 8_000;
/** Token budget for each earlier message in `thread.earlier_messages`. */
export const JEV_EARLIER_MESSAGE_TOKENS = 400;
/** How many earlier messages, newest first, give the latest one its context. */
export const JEV_EARLIER_MESSAGES = 2;

/** Shared facts every question can lean on. Goes into the state once. */
export const READER_NOTE =
  "The reader owns this inbox. `latest_message` is the newest message in the thread and was sent to the reader.";

export interface NoulQuestion {
  type: "noul";
  instructions: string;
  criteria?: { true: string; false: string };
}

